    <p>The easiest way to pick art for a rental is to choose a style first, then one artist inside it, then a size that suits your wall. Hang it with removable hooks rated for its weight, so the walls stay as you found them.</p>

    <p>That is the order I followed in a large bedroom that needed a statement piece.</p>

    <h2>Start with a style, not a painting</h2>

    <p>Browsing thousands of paintings goes nowhere. I read about different art styles until one stayed with me, which was Impressionism. Then I asked ChatGPT for a few directions within that style and followed them until one artist stood out. That was <a href="https://www.britannica.com/biography/Gustave-Caillebotte">Gustave Caillebotte</a>, a French painter who combined aspects of the academic and Impressionist styles.</p>

    <p>Narrowing in this order meant I was comparing paintings I already liked, not paintings in general.</p>

    <h2>Choose the size for the wall</h2>

    <p>My wall is about 4 metres wide. I started with one 20 x 24 inch painting (about 51 x 61 cm). I picked that size because it was reasonably priced and a good test. It looked good enough that I bought more.</p>

    <p>Many guides suggest a piece should fill about <a href="https://urbanroad.com/blogs/guides/wall-art-sizes-a-complete-guide">two thirds of the wall or furniture beneath it</a>. On a 4 metre wall, one 20 x 24 inch painting is well under that. Starting with one piece let me see how it sat in the room before spending on more.</p>

    <h2>Hang it without damaging the wall</h2>

    <p>I hung mine with Large Command Hooks from Coles, stuck straight onto the wall, and they worked well. Check two things before you do. First, weigh the frame, because every hook has a limit: each Large Command hook is <a href="https://www.staples.com/command-large-utility-hook-white-17003-es/product_395690">rated for 5 lb</a>, so a heavier frame needs more than one. Second, check the wall surface, because the adhesive needs a smooth, clean, painted surface. If your painting arrives rolled, here is <a href="https://cavalletto.com.au/blog/how-to-frame-and-hang-a-rolled-painting">how to frame and hang a rolled painting</a>.</p>

