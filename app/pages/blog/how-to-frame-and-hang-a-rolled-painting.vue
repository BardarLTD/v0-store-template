    <p>To frame a rolled painting, you stretch the canvas tight over wooden stretcher bars with a staple gun, then hang it on removable hooks. It is a job for one person and one afternoon, and it takes more effort than you'd expect.</p>

    <p>I did it with a painting that arrived rolled and came with its stretcher bars. This is what it took.</p>

    <h2>What you need</h2>

    <p>I bought a staple gun for $20. That was the main extra cost. The painting came with its stretcher bars, and I also bought a DIY frame that I assembled myself.</p>

    <h2>How to stretch it</h2>

    <p>The method is the standard one for stretching canvas. <a href="https://www.dickblick.com/learning-resources/buying-guides/canvas/how-to-stretch-canvas/">Blick's guide</a> sums it up: staple the centre of one bar, pull the canvas across to the opposite bar and staple its centre, then work toward the corners. After about 12 staples the canvas is taut. Then fill in the gaps, fold the corners neatly and tack the excess canvas to the back.</p>

    <p>The point is to keep pulling the canvas tight before each staple. Slack at the start shows up as wrinkles at the end.</p>

    <h2>What I'd do differently</h2>

    <p>I'd order it already framed. Stretching it myself was a good test and it worked, but it took more effort than I expected, and I'd rather spend that time on something else. At Cavalletto, we now sell paintings pre-framed.</p>

