    <p>Yes, for most people decorating a home, with one condition: you are buying a hand-painted copy of a classic for your wall, not an investment. If you have thousands of dollars to spend, buy an original instead.</p>

    <p>I'm basing that on paintings I bought for my own walls, and on selling them now.</p>

    <h2>What the paint gives you</h2>

    <p>Up close, a hand-painted oil painting has more depth than a print. The paint sits on the surface and catches light in different ways as the day moves, which a flat print doesn't. I also have prints on my walls. In person, the paintings have a lot more detail and depth than the prints do.</p>

    <p>The clearest difference is what visitors do. The paintings get comments. My prints don't get any.</p>

    <h2>What it won't give you</h2>

    <p>A reproduction is a decorative piece, not a collectable. One commenter in a <a href="https://www.reddit.com/r/artcollecting/comments/1o3fmn6/prints_vs_reproductions/">collectors' forum thread</a> puts it plainly: any reproduction, painted or printed, has no real resale value, because collecting is about original works. That is one person's view, but it matches how I treat mine. I bought them to look at, not to sell.</p>

    <p>If you have thousands of dollars to spend and want something that holds value, buy an original.</p>

    <h2>The part that surprised me</h2>

    <p>I bought the cheapest option, which arrives rolled. It needed a staple gun to stretch onto a frame, and that took more effort than I expected. If you'd rather not, buy it already framed. Next time, I would. I cover the steps in <a href="https://cavalletto.com.au/blog/how-to-frame-and-hang-a-rolled-painting">how to frame and hang a rolled painting</a>, and how long the whole thing takes in <a href="https://cavalletto.com.au/blog/how-long-does-a-custom-oil-painting-take">how long a custom oil painting takes</a>.</p>

    <h2>So, is it worth it?</h2>

    <p>It is if you want real paint on your wall at a price well under an original, and you are happy to treat it as décor. It is not if you want an investment.</p>

